const PI_EXTENSION_FILENAME = "webmux-pi-extension.js";

/** The pi extension lives in the webmux storage dir next to `webmux-agentctl`, and is loaded
 *  with `pi -e`, so nothing is written into the worktree. */
export function piExtensionPath(webmuxDir: string): string {
  return join(webmuxDir, PI_EXTENSION_FILENAME);
}

/** pi has no permission prompts, so `yolo` needs no flag. The webmux extension is loaded
 *  with `-e` from the storage dir that holds `runtimeEnvPath` (reachable in containers too). */
function buildPiInvocation(input: BuiltInLaunchInput): string {
  const extension = ` -e ${quoteShell(piExtensionPath(dirname(input.runtimeEnvPath)))}`;
  const systemPrompt = input.systemPrompt ? ` --append-system-prompt ${quoteShell(input.systemPrompt)}` : "";
  const promptArg = input.prompt ? ` ${quoteShell(input.prompt)}` : "";
  const pin = input.pinSessionId ? ` --session-id ${quoteShell(input.pinSessionId)}` : "";

  let session = pin;
  if (input.launchMode === "fork" && input.forkFromSessionId) {
    // `--fork` copies the session into a new one; `--session-id` names that new session.
    session = ` --fork ${quoteShell(input.forkFromSessionId)}${pin}`;
  } else if (input.launchMode === "resume") {
    session = input.resumeConversationId ? ` --session ${quoteShell(input.resumeConversationId)}` : " --continue";
  }
  return `pi${extension}${systemPrompt}${session}${promptArg}`;
}

/** pi stores sessions under `<agent dir>/sessions/--<cwd with separators as dashes>--/`. */
function encodePiSessionDir(cwd: string): string {
  return `--${cwd.replace(/^[/\\]/, "").replace(/[/\\:]/g, "-")}--`;
}

async function readPiSessionId(path: string): Promise<string | null> {
  try {
    const head = await Bun.file(path).slice(0, 4096).text();
    const parsed: unknown = JSON.parse(head.split("\n", 1)[0] ?? "");
    if (isRecord(parsed) && parsed.type === "session" && typeof parsed.id === "string") return parsed.id;
  } catch {
    // Fall back to the `<timestamp>_<id>.jsonl` file name.
  }
  return basename(path, ".jsonl").split("_").slice(1).join("_") || null;
}

async function listPiSessionIds(cwd: string): Promise<string[]> {
  const agentDir = Bun.env.PI_CODING_AGENT_DIR ?? join(home(), ".pi", "agent");
  const dir = join(agentDir, "sessions", encodePiSessionDir(cwd));
  const names = await readdir(dir).catch((): string[] => []);
  const stamped = await Promise.all(
    names
      .filter((name) => name.endsWith(".jsonl"))
      .map(async (name): Promise<StampedSession | null> => {
        const path = join(dir, name);
        const [info, sessionId] = await Promise.all([stat(path).catch(() => null), readPiSessionId(path)]);
        return info && sessionId ? { sessionId, mtimeMs: info.mtimeMs } : null;
      }),
  );
  return newestFirst(stamped.filter((entry): entry is StampedSession => entry !== null));
}

/** Lifecycle reporting for pi goes through an extension that shells out to the same
 *  `webmux-agentctl` the other agents' hooks use. */
function buildPiExtension(input: { agentCtlPath: string }): string {
  return `// Generated by webmux — do not edit. Reports pi lifecycle events to the dashboard.
import { spawn, spawnSync } from "node:child_process"

const AGENTCTL = ${JSON.stringify(input.agentCtlPath)}

let reportedLifecycle = null

// Lifecycle reports are sent synchronously, in event order, so a late in-flight "running"
// report can never land after the turn-end report.
function reportLifecycle(args, lifecycle) {
  if (reportedLifecycle === lifecycle) return
  reportedLifecycle = lifecycle
  spawnSync(AGENTCTL, args, { stdio: "ignore" })
}

// Payload reports carry no state, so they stay off the event loop. Detached so the report
// still lands when pi exits right after the tool call that triggered it.
function notify(args, payload) {
  const child = spawn(AGENTCTL, args, { stdio: ["pipe", "ignore", "ignore"], detached: true })
  // A missing or unwritable agentctl must never take the agent's turn down with it.
  child.on("error", () => {})
  if (child.stdin) {
    child.stdin.on("error", () => {})
    child.stdin.end(JSON.stringify(payload))
  }
  child.unref()
}

export default function (pi) {
  // Fires on every start, including resumes: the "agent is up" signal.
  pi.on("session_start", async () => {
    reportLifecycle(["status-changed", "--lifecycle", "idle", "--best-effort"], "idle")
  })
  pi.on("agent_start", async () => {
    reportLifecycle(["status-changed", "--lifecycle", "running", "--best-effort"], "running")
  })
  // agent_settled, not agent_end: it fires only once retries, compaction and queued
  // follow-ups are done, so the turn is really over.
  pi.on("agent_settled", async () => {
    reportLifecycle(["agent-stopped"], "stopped")
  })
  pi.on("tool_result", async (event) => {
    if (event.toolName !== "bash") return
    notify(["pi-post-tool-use"], {
      tool_name: event.toolName,
      tool_input: event.input,
      tool_response: { content: event.content, details: event.details },
    })
  })
}
`;
}

async function writePiRuntimeArtifacts(ctx: RuntimeArtifactsContext): Promise<void> {
  await Bun.write(piExtensionPath(ctx.webmuxDir), buildPiExtension({ agentCtlPath: ctx.agentCtlPath }));
}

function buildPiInitCommand(prompt: InitPromptSpec): InitAgentCommandSpec {
  return {
    agent: "pi",
    cmd: "pi",
    // pi has no permission prompts, so editing .webmux.yaml needs no approval flag.
    args: ["--mode", "json", "--append-system-prompt", prompt.systemPrompt, prompt.userPrompt],
  };
}

/** `pi --mode json` emits session events: `message_update` carries text deltas and
 *  `tool_execution_start` carries the tool call. */
function parsePiStreamLine(
  raw: Record<string, unknown>,
  state: InitAgentStreamState,
): InitAgentStreamEvent[] {
  const type = readString(raw.type) ?? "unknown";

  if (type === "message_update" && isRecord(raw.assistantMessageEvent)) {
    const event = raw.assistantMessageEvent;
    if (event.type === "text_delta" && typeof event.delta === "string") {
      return streamSnapshot(state, state.assistantSnapshot + event.delta);
    }
    return [];
  }

  if (type === "tool_execution_start") {
    const args = isRecord(raw.args) ? raw.args : null;
    const command = args ? extractCommandText(args.command) : null;
    const toolName = readString(raw.toolName);
    if (command) return emitStatus(state, `Running ${truncateText(command)}`);
    if (toolName) return emitStatus(state, `Using ${toolName}...`);
  }

  if (type === "message_end" || type === "turn_end") {
    return closeAssistant(state);
  }

  return [];
}

