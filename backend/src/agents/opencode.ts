import { mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { isRecord } from "../lib/type-guards";
import { newestFirst, quoteShell, type StampedSession } from "./shared";
import type { AgentAdapter, BuiltInLaunchInput, RuntimeArtifactsContext } from "./types";

/** File the opencode launch command writes the profile system prompt to, referenced from
 *  `OPENCODE_CONFIG_CONTENT.instructions` because opencode has no `--append-system-prompt`. */
export function opencodeInstructionsPath(worktreePath: string): string {
  return join(worktreePath, ".opencode", "webmux-instructions.md");
}

/** Session ids the generated opencode plugin records, newest last. opencode keeps its
 *  transcripts in a database rather than per-session files, so this is what session
 *  discovery reads instead of scanning a well-known agent directory. */
export function opencodeSessionsPath(worktreePath: string): string {
  return join(worktreePath, ".opencode", "webmux-sessions.jsonl");
}

/** opencode has no `--append-system-prompt`: the only way to add instructions to a launch is
 *  to point the resolved config at an extra instructions file, so the launch writes one.
 *  `OPENCODE_CONFIG_CONTENT` is merged over the user's own opencode config. */
function buildOpencodeInstructionsPrefix(systemPrompt: string, worktreePath: string): string {
  const instructionsPath = opencodeInstructionsPath(worktreePath);
  const inlineConfig = JSON.stringify({ instructions: [instructionsPath] });
  return `printf '%s' ${quoteShell(systemPrompt)} > ${quoteShell(instructionsPath)}; `
    + `OPENCODE_CONFIG_CONTENT=${quoteShell(inlineConfig)} `;
}

function buildOpencodeInvocation(input: BuiltInLaunchInput): string {
  const prefix = input.systemPrompt
    ? buildOpencodeInstructionsPrefix(input.systemPrompt, input.worktreePath)
    : "";
  // `--auto` approves every permission that isn't explicitly denied by the user's config.
  const autoFlag = input.yolo ? " --auto" : "";
  // `--prompt` is submitted as the first turn while the TUI boots, so there is no
  // paste/Enter race — the same reason claude and codex take the prompt on the CLI.
  const promptFlag = input.prompt ? ` --prompt ${quoteShell(input.prompt)}` : "";

  if (input.launchMode === "fork" && input.forkFromSessionId) {
    // `--fork` copies the session's history into a brand new session.
    return `${prefix}opencode${autoFlag} --session ${quoteShell(input.forkFromSessionId)} --fork${promptFlag}`;
  }
  if (input.launchMode === "resume") {
    const resumeTarget = input.resumeConversationId
      ? ` --session ${quoteShell(input.resumeConversationId)}`
      : " --continue";
    return `${prefix}opencode${autoFlag}${resumeTarget}${promptFlag}`;
  }
  return `${prefix}opencode${autoFlag}${promptFlag}`;
}

async function listOpencodeSessionIds(cwd: string): Promise<string[]> {
  const file = Bun.file(opencodeSessionsPath(cwd));
  const content = await file.text().catch((): string => "");
  const stamped = content
    .split("\n")
    .filter((line) => line.trim().length > 0)
    .map((line): StampedSession | null => {
      try {
        const parsed: unknown = JSON.parse(line);
        if (!isRecord(parsed)) return null;
        const { id, at } = parsed;
        return typeof id === "string" && typeof at === "number" ? { sessionId: id, mtimeMs: at } : null;
      } catch {
        return null;
      }
    })
    .filter((entry): entry is StampedSession => entry !== null);

  return newestFirst(stamped);
}

export function opencodePluginPath(worktreePath: string): string {
  return join(worktreePath, ".opencode", "plugin", "webmux.js");
}

/** opencode has no shell-hook config: lifecycle reporting goes through a generated plugin
 *  that shells out to the same `webmux-agentctl` the Claude and Codex hooks use. */
function buildOpencodePlugin(input: { agentCtlPath: string; sessionsPath: string }): string {
  return `// Generated by webmux — do not edit. Reports opencode lifecycle events to the dashboard.
import { spawn, spawnSync } from "node:child_process"
import { appendFileSync } from "node:fs"

const AGENTCTL = ${JSON.stringify(input.agentCtlPath)}
const SESSIONS_PATH = ${JSON.stringify(input.sessionsPath)}

let reportedLifecycle = null

// Lifecycle reports are sent synchronously, in event order. opencode emits a last "busy"
// status alongside the end of a turn, and an in-flight async report of it would land after
// the turn-end report and leave the dashboard stuck on "running".
function reportLifecycle(args, lifecycle) {
  if (reportedLifecycle === lifecycle) return
  reportedLifecycle = lifecycle
  spawnSync(AGENTCTL, args, { stdio: "ignore" })
}

// Payload reports carry no state, so they stay off the event loop. Detached so the report
// still lands when opencode exits right after the tool call that triggered it.
function notify(args, payload) {
  const child = spawn(AGENTCTL, args, { stdio: ["pipe", "ignore", "ignore"], detached: true })
  // A missing or unwritable agentctl must never take the agent's turn down with it.
  child.on("error", () => {})
  if (child.stdin) {
    child.stdin.on("error", () => {})
    child.stdin.end(JSON.stringify(payload))
  }
  child.unref()
}

export const WebmuxBridge = async () => {
  // Runs once per opencode start, including \`--session\`/\`--continue\` resumes, which emit
  // no session events until the first turn. This is the "agent is up" signal.
  reportLifecycle(["status-changed", "--lifecycle", "idle", "--best-effort"], "idle")

  return {
    event: async ({ event }) => {
      const props = event.properties
      // Subagents get their own sessions in the same process; only top-level ones
      // (no parent) are sessions webmux can resume or fork.
      if (event.type === "session.created") {
        if (props.info && !props.info.parentID) {
          appendFileSync(SESSIONS_PATH, JSON.stringify({ id: props.sessionID, at: Date.now() }) + "\\n")
        }
        return
      }
      // Only "busy" is forwarded: session.idle is what ends a turn, and the idle side of
      // session.status fires alongside it.
      if (event.type === "session.status") {
        if (props.status && props.status.type === "busy") {
          reportLifecycle(["status-changed", "--lifecycle", "running", "--best-effort"], "running")
        }
        return
      }
      if (event.type === "session.idle") {
        reportLifecycle(["agent-stopped"], "stopped")
        return
      }
      if (event.type === "permission.asked") {
        reportLifecycle(["status-changed", "--lifecycle", "idle", "--best-effort"], "idle")
      }
    },
    "tool.execute.after": async (input, output) => {
      if (input.tool !== "bash") return
      notify(["opencode-post-tool-use"], {
        tool_name: input.tool,
        tool_input: input.args,
        tool_response: output,
      })
    },
  }
}
`;
}

async function writeOpencodeRuntimeArtifacts(ctx: RuntimeArtifactsContext): Promise<void> {
  const pluginPath = opencodePluginPath(ctx.worktreePath);
  await mkdir(dirname(pluginPath), { recursive: true });
  // The plugin file is webmux-owned, so it is rewritten rather than merged.
  await Bun.write(
    pluginPath,
    buildOpencodePlugin({
      agentCtlPath: ctx.agentCtlPath,
      sessionsPath: opencodeSessionsPath(ctx.worktreePath),
    }),
  );
}

export const opencodeAdapter: AgentAdapter = {
  id: "opencode",
  label: "opencode",
  capabilities: {
    terminal: true,
    // opencode keeps its transcripts in its own database rather than on-disk session
    // files, so dashboard chat has no history to read yet — the terminal is the surface.
    inAppChat: false,
    conversationHistory: false,
    interrupt: false,
    resume: true,
  },
  chatProvider: null,
  supportsPinnedSessionId: false,
  generatedArtifactExcludes: [
    ".opencode/plugin/webmux.js",
    ".opencode/webmux-instructions.md",
    ".opencode/webmux-sessions.jsonl",
  ],
  writeRuntimeArtifacts: writeOpencodeRuntimeArtifacts,
  buildCommand: buildOpencodeInvocation,
  listSessionIds: listOpencodeSessionIds,
};
